MARKER = "# Managed by devkit hook dispatcher"
GATE_MARKER = "# Managed by devkit gate"
LEGACY_MARKER = "# Managed by devkit legacy adapter"
# Where a foreign hook is preserved beside the dispatcher. Never ``.legacy``: the pre-commit framework moves a hook it
# did not write there and its own hook runs that file first, so a pre-commit hook preserved under that name runs itself.
PRESERVED_SUFFIX = ".devkit-preserved"
# The pre-commit framework's migration-mode name; earlier devkit versions also preserved hooks under it.
PRE_COMMIT_LEGACY_SUFFIX = ".legacy"
# The second line of every hook script the pre-commit framework writes.
PRE_COMMIT_SIGNATURE = "# File generated by pre-commit"
DEVKIT_ENTRY = "20-devkit"
LEGACY_ENTRY = "00-legacy"
PRE_COMMIT_ENTRY = "10-pre-commit"  # a pre-commit framework hook, chained as an entry of the dispatcher
PYTHON_LINE = "python="
HOOKS_PATH_KEY = "core.hooksPath"
LOCK_FILE = "devkit-hooks.lock"
_PYTHON_CHECK_TIMEOUT = 60.0
# Ends the quoted here-document a generated script prints an advisory block with.
_ADVISORY_DELIMITER = "DEVKIT_ADVISORY"


class HookState(StrEnum):
    MISSING = "missing"
    MANAGED = "managed"
    FOREIGN = "foreign"  # an executable hook, a symbolic link, or anything that is not a regular file
    INERT = "inert"  # a regular file Git ignores because it is not executable


@dataclass(frozen=True)
class HookStatus:
    stage: Stage
    path: Path
    state: HookState
    python: str | None = None  # fallback recorded by the managed 20-devkit entry, absent on empty stages
    backup: bool = False  # a foreign hook is preserved at ``<hook>.devkit-preserved``
    scripts: tuple[str, ...] = ()

    @property
    def python_ok(self) -> bool:
        if self.python is None:
            return False
        path = Path(self.python)
        return path.is_absolute() and path.is_file() and os.access(path, os.X_OK)


@dataclass(frozen=True)
class HooksLocation:
    directory: Path  # ``<common-git-dir>/hooks``
    hooks_path: str | None = None  # ``core.hooksPath`` when it sends Git to another directory
    hooks_path_scope: str | None = None  # the configuration scope that sets ``hooks_path``


def _present(path: Path) -> bool:
    return path.is_symlink() or path.exists()


def _backup(path: Path) -> Path:
    return path.with_name(path.name + PRESERVED_SUFFIX)


def _pre_commit_legacy(path: Path) -> Path:
    return path.with_name(path.name + PRE_COMMIT_LEGACY_SUFFIX)


def generated_by_pre_commit(path: Path) -> bool:
    """Whether ``path`` is a regular hook script the pre-commit framework wrote (``pre-commit install``)."""
    if path.is_symlink() or not path.is_file():
        return False
    try:
        with path.open("rb") as handle:
            head = handle.read(4096).decode("utf-8", errors="replace")
    except OSError:
        return False
    return any(line.startswith(PRE_COMMIT_SIGNATURE) for line in head.splitlines())


def locate(cwd: Path) -> HooksLocation:
    """The managed hooks directory and the ``core.hooksPath`` override that bypasses it, if any."""
    directory = git.common_git_dir(cwd) / "hooks"
    custom = git.config_value(cwd, HOOKS_PATH_KEY)
    if custom:
        # Git runs hooks from the work tree's top level, so a relative value is relative to it.
        candidate = Path(custom).expanduser()
        if not candidate.is_absolute():
            candidate = require_git_toplevel(cwd) / candidate
        if candidate.resolve() == directory.resolve():
            custom = None
    return HooksLocation(directory, custom, git.config_scope(cwd, HOOKS_PATH_KEY) if custom else None)


def _advisory_block(error: AdvisoryError) -> str:
    """``error``'s sentinel block, as a generated script prints it, one ``\\n``-terminated line each."""
    return "".join(f"{line}\n" for line in error.lines())


def dispatcher_script(stage: Stage) -> str:
    """Run executable direct children of ``<stage>.d`` in bytewise filename order, without changing the Git environment.

    The entries are found beside the dispatcher by the stage's name, not by ``$0``, so a dispatcher another tool
    renamed (pre-commit's migration mode moves it to ``<stage>.legacy``) still runs them. Run that way, with
    ``PRE_COMMIT_RUNNING_LEGACY`` set, it skips entries the pre-commit framework wrote: pre-commit runs its own hooks
    after this one, and its script refuses to run inside its own migration mode.

    ``post-commit`` reports a failed script as ``GATE_HOOK_SCRIPT_FAILED``, rendered here by the advisory
    library; the script path and exit status follow as ``[DETAIL]`` lines at run time.
    """
    if stage.blocking:
        failure, report = 'exit "$code"', ""
    else:
        failed = _advisory_block(HookScriptFailedNotice("hook script failed"))
        failure = 'report_failure "$script" "$code"'
        report = f"""report_failure() {{
    cat >&2 <<'{_ADVISORY_DELIMITER}'
{failed}{_ADVISORY_DELIMITER}
    printf '[DETAIL] stage={stage} script=%s exit=%s\\n' "$1" "$2" >&2
}}
"""
    # A function keeps the original hook arguments separate from the script path.
    return f"""#!/bin/sh
{MARKER}
entries="$(dirname "$0")/{stage}.d"
run_script() {{
    script=$1
    shift
    [ -f "$script" ] && [ -x "$script" ] || return 0
    if [ -n "${{PRE_COMMIT_RUNNING_LEGACY:-}}" ] && grep -q '^{PRE_COMMIT_SIGNATURE}' "$script" 2>/dev/null; then
        return 0
    fi
    "$script" "$@"
    code=$?
    if [ "$code" -ne 0 ]; then
        {failure}
    fi
}}
{report}if [ "${{LC_ALL+x}}" = x ]; then
    saved_lc_all=$LC_ALL
    had_lc_all=yes
else
    had_lc_all=no
fi
LC_ALL=C
export LC_ALL
for entry in "$entries"/*; do
    if [ "$had_lc_all" = yes ]; then
        LC_ALL=$saved_lc_all
        export LC_ALL
    else
        unset LC_ALL
    fi
    run_script "$entry" "$@"
done
exit 0
"""


def legacy_script(stage: Stage) -> str:
    return f"""#!/bin/sh
{LEGACY_MARKER}
legacy="$(dirname "$0")/../{stage}{PRESERVED_SUFFIX}"
if [ -f "$legacy" ] && [ -x "$legacy" ]; then
    exec "$legacy" "$@"
fi
exit 0
"""


def _unavailable(stage: Stage) -> GateInterpreterError:
    """The advisory a ``20-devkit`` entry prints when no interpreter can import ``devkit_agt.features.gate``."""
    error = GateInterpreterError(f"{stage}: no interpreter can import devkit_agt.features.gate; the gates did not run")
    return error if stage.blocking else error.with_level(Level.WARNING)


def _bootstrap(block: str, code: int) -> str:
    """``python -m devkit_agt.features.gate`` in the same process, reporting a failed import as the advisory ``block``.

    One interpreter start-up per hook: the import is checked where the stage runs, rather than in a
    second process first. Without it, an interpreter that cannot import devkit exits ``1`` with a
    traceback, which reads as gates refusing the commit.
    """
    return f"""import runpy, sys
try:
    import devkit_agt.features.gate.cli
except Exception as exc:
    reason = (str(exc).splitlines() or [""])[0]
    sys.stderr.write({block!r} + "[DETAIL] python=" + sys.executable + "\\n[DETAIL] " + type(exc).__name__ + ": " + reason + "\\n")
    sys.exit({code})
sys.argv[1:1] = ["run"]
runpy.run_module("devkit_agt.features.gate", run_name="__main__", alter_sys=True)
"""


def wrapper_script(stage: Stage, python: str) -> str:
    """The ``20-devkit`` entry, with an absolute fallback interpreter.

    When the selected interpreter is missing or cannot import ``devkit_agt.features.gate``, the entry prints
    ``GATE_INTERPRETER_UNAVAILABLE`` and exits ``2`` in a blocking stage, ``0`` in ``post-commit``.
    """
    unavailable = _unavailable(stage)
    code = int(unavailable.exit_code)
    block = _advisory_block(unavailable)
    return f"""#!/bin/sh
{GATE_MARKER}
{PYTHON_LINE}{shlex.quote(python)}
top=$(git rev-parse --show-toplevel 2>/dev/null)
if [ -n "$top" ]; then
    candidate="$top/.venv/bin/python"
    if [ -x "$candidate" ]; then
        for info in "$top"/.venv/lib/python*/site-packages/devkit_agt-*.dist-info; do
            if [ -d "$info" ]; then
                python=$candidate
                break
            fi
        done
    fi
fi
if [ ! -x "$python" ]; then
    cat >&2 <<'{_ADVISORY_DELIMITER}'
{block}{_ADVISORY_DELIMITER}
    printf '[DETAIL] python=%s\\n[DETAIL] not an executable file\\n' "$python" >&2
    exit {code}
fi
bootstrap={shlex.quote(_bootstrap(block, code))}
exec "$python" -P -c "$bootstrap" {stage} "$@"
"""


def _read_python(text: str) -> str | None:
    for line in text.splitlines():
        if line.startswith(PYTHON_LINE):
            parts = shlex.split(line[len(PYTHON_LINE) :])
            return parts[0] if parts else None
    return None


def _state(path: Path) -> tuple[HookState, str | None]:
    if not _present(path):
        return HookState.MISSING, None
    if path.is_symlink() or not path.is_file():
        return HookState.FOREIGN, None
    try:
        text = path.read_text("utf-8", errors="replace")
    except OSError:
        return HookState.FOREIGN, None
    if MARKER in text.splitlines():
        return HookState.MANAGED, _read_python(text)
    if not os.access(path, os.X_OK):
        return HookState.INERT, None
    return HookState.FOREIGN, None


def status(cwd: Path, location: HooksLocation | None = None) -> list[HookStatus]:
    directory = (location or locate(cwd)).directory
    result: list[HookStatus] = []
    for stage in Stage:
        path = directory / stage.value
        state, python = _state(path)
        entries = path.with_name(path.name + ".d")
        scripts = tuple(sorted(child.name for child in entries.iterdir())) if entries.is_dir() else ()
        entry = entries / DEVKIT_ENTRY
        if state is HookState.MANAGED:
            python = _read_python(entry.read_text("utf-8", errors="replace")) if entry.is_file() else None
        result.append(HookStatus(stage, path, state, python, _present(_backup(path)), scripts))
    return result


def _enabled_gates(project: GateProject, stage: Stage) -> list[str]:
    return [gate.id for gate in project.registry.for_stage(stage) if project.config.enabled(gate)]


def missing_entry_notices(
    project: GateProject, statuses: Sequence[HookStatus], location: HooksLocation | None = None
) -> list[AdvisoryError]:
    """Warnings for enabled gates that do not run at commit time.

    A stage's gates run only through its managed dispatcher and that dispatcher's ``20-devkit`` entry,
    which ``install`` writes for the stages with enabled gates when it runs: one ``GATE_HOOK_ENTRY_MISSING``
    per stage without them (a gate of another stage enabled later in the configuration does not run until
    the next install or sync). When ``location`` has a ``core.hooksPath`` that sends Git elsewhere, no
    managed hook runs at all, and ``install`` refuses: one ``GATE_HOOKS_PATH_SET`` warning names every
    enabled gate instead, with the fix that clears the setting.
    """
    if location is not None and location.hooks_path:
        gates = [gate for stage in Stage for gate in _enabled_gates(project, stage)]
        if not gates:
            return []
        notice = _hooks_path_error(location, f"gates={','.join(gates)}", prefix="enabled gates do not run: ")
        return [notice.with_level(Level.WARNING)]
    by_stage = {item.stage: item for item in statuses}
    stages: list[str] = []
    details: list[str] = []
    targets: list[str] = []
    for stage in Stage:
        gates = _enabled_gates(project, stage)
        item = by_stage.get(stage)
        if not gates or item is None:
            continue
        entry = _entries(item.path) / DEVKIT_ENTRY
        if item.state is not HookState.MANAGED and not chained_by_pre_commit(item.path):
            problem = f"the {stage} hook is not a devkit dispatcher ({item.state})"
        elif not (_owned(entry, GATE_MARKER) and os.access(entry, os.X_OK)):
            problem = f"{entry.parent.name}/{DEVKIT_ENTRY} is not installed"
        else:
            continue
        stages.append(str(stage))
        details.append(f"{stage}: {problem}; gates={','.join(gates)}")
        targets.append(str(entry))
    if not stages:
        return []
    return [
        HookEntryMissingNotice(
            f"enabled gates do not run in {', '.join(stages)}: the hook entry is missing",
            *details,
            target_files=targets,
        )
    ]


def chained_by_pre_commit(path: Path) -> bool:
    """Whether the hook at ``path`` is pre-commit's, running devkit's dispatcher as its migration-mode legacy hook.

    ``pre-commit install`` after devkit moves the dispatcher to ``<hook>.legacy``; it still runs the stage's
    entries, and the next install or sync makes it the hook again.
    """
    return generated_by_pre_commit(path) and _owned(_pre_commit_legacy(path), MARKER)


def check_python(python: str) -> str:
    """The absolute form of ``python`` (POSIX separators) after checking it can import ``devkit_agt.features.gate``."""
    candidate = Path(os.path.abspath(Path(python).expanduser()))
    if not (candidate.is_file() and os.access(candidate, os.X_OK)):
        raise GatePythonError(f"--python {python}: not an executable file")
    try:
        completed = subprocess.run(
            [str(candidate), "-P", "-c", "import devkit_agt.features.gate"],
            capture_output=True,
            text=True,
            check=False,
            timeout=_PYTHON_CHECK_TIMEOUT,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise GatePythonError(f"--python {python}: cannot be run: {exc}") from exc
    if completed.returncode != 0:
        last = (completed.stderr.strip().splitlines() or [f"exit status {completed.returncode}"])[-1]
        raise GatePythonError(f"--python {python}: cannot import devkit_agt.features.gate", last)
    return candidate.as_posix()


def _write(path: Path, text: str, *, dry_run: bool = False) -> bool:
    """Replace ``path`` with an executable (``0o755``) LF-only file without following a link at ``path``.

    Returns whether the file changed (on a dry run: would change); an identical executable file is left untouched.
    """
    data = text.encode("utf-8")
    if path.is_file() and not path.is_symlink() and path.read_bytes() == data and os.access(path, os.X_OK):
        return False
    if not dry_run:
        atomic_write_bytes(path, data, mode=0o755)
    return True


def _hooks_path_fix(location: HooksLocation) -> str:
    """The step that stops ``core.hooksPath`` bypassing the managed directory, by the scope that sets it."""
    scope = location.hooks_path_scope
    install = devkit_command("gate install")
    if scope == "local":
        return f"git config --unset {HOOKS_PATH_KEY} && {install}"
    if scope == "worktree":
        return f"git config --worktree --unset {HOOKS_PATH_KEY} && {install}"
    if scope == "command":
        return (
            f"Remove {HOOKS_PATH_KEY} from the `git -c` options or GIT_CONFIG_* environment variables, "
            f"then run `{install}`"
        )
    # global or system: override it for this repository only, leaving other repositories untouched
    return f"git config {HOOKS_PATH_KEY} {shlex.quote(location.directory.as_posix())} && {install}"


def _hooks_path_error(location: HooksLocation, *details: str, prefix: str = "") -> HooksPathSetError:
    """``GATE_HOOKS_PATH_SET`` for the ``core.hooksPath`` of ``location``, its message after ``prefix``."""
    scope = f" ({location.hooks_path_scope} config)" if location.hooks_path_scope else ""
    return HooksPathSetError(
        f"{prefix}{HOOKS_PATH_KEY} is set to {location.hooks_path!r}{scope}; managed hooks are only installed into "
        f"{location.directory}, which Git would not run",
        *details,
        fix=_hooks_path_fix(location),
    )


def _refuse_hooks_path(location: HooksLocation) -> None:
    if location.hooks_path:
        raise _hooks_path_error(location)


@dataclass
class InstallResult:
    """What ``install`` changed (or, on a dry run, would change), one line per change; empty when nothing changed."""

    actions: list[str] = field(default_factory=list)
    notices: list[AdvisoryError] = field(default_factory=list)
    hooks_dir: Path | None = None  # the directory Git runs hooks from, where each ``<stage>`` hook lives


@contextmanager
def clone_lock(common_git_dir: Path) -> Iterator[None]:
    """Serialize hook and ``devkit.config`` template mutations across linked worktrees of the same clone.

    An exclusive ``devkit_core.core.file_lock`` on ``<common_git_dir>/devkit-hooks.lock``, waited for without
    a bound and held until the block ends. A lock file that is a symlink or not a regular file is
    ``UnsafePathError`` (``PATH_UNSAFE``).
    """
    with file_lock(common_git_dir / LOCK_FILE):
        yield


def _owned(path: Path, marker: str) -> bool:
    return path.is_file() and not path.is_symlink() and marker in path.read_text("utf-8", errors="replace").splitlines()


def _entries(path: Path) -> Path:
    return path.with_name(path.name + ".d")


class _Move(StrEnum):
    """Where ``install`` puts a hook it takes over."""

    PRESERVE = "preserve"  # beside the dispatcher, as ``<hook>.devkit-preserved``, run by ``00-legacy``
    ENTRY = "entry"  # a pre-commit framework hook, as the ``10-pre-commit`` entry
    REMOVE = "remove"  # devkit's own dispatcher, left at ``<hook>.legacy`` by pre-commit's migration mode


@dataclass(frozen=True)
class _Plan:
    item: HookStatus
    hook: _Move | None = None  # what happens to the file at the hook path
    legacy: _Move | None = None  # what happens to ``<hook>.legacy``


def _plan(item: HookStatus) -> _Plan:
    """Where the hook and its ``<hook>.legacy`` go, so the dispatcher runs every hook that ran before, once.

    A pre-commit framework hook becomes an entry, where it finds no ``<hook>.legacy`` to run; another foreign hook is
    preserved beside the dispatcher. ``<hook>.legacy`` is devkit's dispatcher after ``pre-commit install`` (removed),
    a pre-commit hook an earlier devkit preserved (an entry), or a hook that the replaced hook ran (pre-commit's
    migration mode) or an earlier devkit preserved (preserved; also when the dispatcher was deleted while devkit's
    adapter still chains it). Anything else is left alone.
    """
    moving = item.state in (HookState.FOREIGN, HookState.INERT)
    framework = moving and generated_by_pre_commit(item.path)
    hook = _Move.ENTRY if framework else _Move.PRESERVE if moving else None
    old = _pre_commit_legacy(item.path)
    legacy: _Move | None = None
    if _present(old):
        if _owned(old, MARKER):
            legacy = _Move.REMOVE
        elif generated_by_pre_commit(old):
            legacy = _Move.ENTRY if item.state in (HookState.MANAGED, HookState.MISSING) else None
        elif item.state is HookState.MANAGED or framework or (item.state is HookState.MISSING and _adapted(item)):
            legacy = _Move.PRESERVE
    return _Plan(item, hook, legacy)


def _adapted(item: HookStatus) -> bool:
    """Whether a devkit adapter runs a preserved hook of the stage: an earlier one ran ``<hook>.legacy``, also after
    the dispatcher itself was deleted by hand."""
    return _owned(_entries(item.path) / LEGACY_ENTRY, LEGACY_MARKER)


class InstallHooksUseCase(BaseUseCase):
    """Application entrypoint for install."""

    def execute(
        self,
        cwd: Path,
        python: str,
        *,
        force: bool = False,
        preserve_python: bool = False,
        dry_run: bool = False,
    ) -> InstallResult:
        """Install dispatchers and ``20-devkit`` entries, preserving regular foreign hooks automatically.

        ``force`` also permits moving symlinks or non-regular hooks. Preflight all stages before writing;
        reserved entry collisions, existing preserved hooks and custom ``core.hooksPath`` are always refused.
        Automatic sync uses ``preserve_python`` to retain each valid existing fallback under the clone lock.
        ``dry_run`` runs the same checks and reports the changes without making them.
        """
        location = locate(cwd)
        _refuse_hooks_path(location)
        recorded = check_python(python)
        project = load_gate_project(cwd)
        # Invalid configuration must still be reported by the hooks, rather than silently bypassed.
        stages = (
            set(Stage)
            if not project.validation.ok
            else {gate.stage for gate in project.registry.get_all() if project.config.enabled(gate)}
        )
        # A dry run writes nothing, not even the lock file; a concurrent install can only make its plan stale.
        with nullcontext() if dry_run else clone_lock(location.directory.parent):
            current = status(cwd, location)
            plans = [_plan(item) for item in current]
            moving = [plan.item for plan in plans if plan.hook is not None]
            special = [item for item in moving if item.path.is_symlink() or not item.path.is_file()]
            if special and not force:
                raise ForeignHookError(
                    "hooks are symbolic links or non-regular files",
                    *(str(item.path) for item in special),
                    fix=devkit_command("gate install --force"),
                    target_files=[str(item.path) for item in special],
                )
            blocked = [plan.item for plan in plans if plan.item.backup and _Move.PRESERVE in (plan.hook, plan.legacy)]
            if blocked:
                raise HookBackupExistsError(
                    "a preserved hook already exists",
                    *(str(_backup(item.path)) for item in blocked),
                    fix=f"Move the conflicting preserved hooks to another path, then run `{devkit_command('sync')}`",
                    target_files=[str(_backup(item.path)) for item in blocked],
                )
            if location.directory.is_symlink():
                raise HookLayoutError("hooks directory is a symbolic link", str(location.directory))
            for plan in plans:
                entries = _entries(plan.item.path)
                if entries.is_symlink() or (_present(entries) and not entries.is_dir()):
                    raise HookLayoutError("hook script directory is not a regular directory", str(entries))
                for name, marker in ((DEVKIT_ENTRY, GATE_MARKER), (LEGACY_ENTRY, LEGACY_MARKER)):
                    entry = entries / name
                    if _present(entry) and not _owned(entry, marker):
                        raise HookLayoutError("reserved hook entry is not managed by devkit", str(entry))
                entry = entries / PRE_COMMIT_ENTRY
                if _Move.ENTRY in (plan.hook, plan.legacy) and _present(entry) and not generated_by_pre_commit(entry):
                    raise HookLayoutError(
                        "the pre-commit framework's hook entry is taken by another script", str(entry)
                    )
            fallbacks: dict[str, str] = {}
            if preserve_python:
                for item in current:
                    if item.python and item.python not in fallbacks:
                        try:
                            fallbacks[item.python] = check_python(item.python)
                        except GatePythonError:
                            fallbacks[item.python] = recorded
            if not dry_run:
                location.directory.mkdir(parents=True, exist_ok=True)
            result = InstallResult(hooks_dir=location.directory)
            for plan in plans:
                self._install_stage(plan, stages, fallbacks.get(plan.item.python or "", recorded), result, dry_run)
            return result

    @staticmethod
    def _install_stage(plan: _Plan, stages: set[Stage], python: str, result: InstallResult, dry_run: bool) -> None:
        item = plan.item
        stage, path = item.stage, item.path
        entries, old, preserved = _entries(path), _pre_commit_legacy(path), _backup(path)
        framework = entries / PRE_COMMIT_ENTRY
        moves: list[str] = []
        notices: list[AdvisoryError] = []
        if not dry_run:
            entries.mkdir(exist_ok=True)
        changed = False
        adapter = entries / LEGACY_ENTRY
        if _Move.PRESERVE in (plan.hook, plan.legacy) or _present(preserved):
            # Rewritten even when present: an earlier adapter ran ``<hook>.legacy``, which may now be the dispatcher.
            changed |= _write(adapter, legacy_script(stage), dry_run=dry_run)
        elif _owned(adapter, LEGACY_MARKER):
            moves.append(f"{stage}: removed {entries.name}/{LEGACY_ENTRY}, which no preserved hook needs")
            if not dry_run:
                adapter.unlink()
        if stage in stages:
            changed |= _write(entries / DEVKIT_ENTRY, wrapper_script(stage, python), dry_run=dry_run)
        # A move that returns a GATE_HOOK_PRESERVED warning is reported by it alone; a dry run returns the line.
        if plan.hook is _Move.PRESERVE:
            kind = "inert (non-executable) hook" if item.state is HookState.INERT else "existing hook"
            if dry_run:
                moves.append(f"{stage}: moved {kind} to {preserved.name}")
            notices.append(
                HookPreservedNotice(
                    f"{kind.replace('hook', f'{stage} hook')} preserved at {preserved}",
                    f"The preserved hook runs first through {entries / LEGACY_ENTRY}; its executable mode is unchanged",
                    target_files=[str(preserved)],
                )
            )
        elif plan.hook is _Move.ENTRY:
            if dry_run:
                moves.append(f"{stage}: moved the pre-commit framework hook to {entries.name}/{PRE_COMMIT_ENTRY}")
            notices.append(
                HookPreservedNotice(
                    f"pre-commit framework {stage} hook chained at {framework}",
                    "The dispatcher runs it before the devkit gates; `pre-commit install` again is safe",
                    target_files=[str(framework)],
                )
            )
        if plan.legacy is _Move.PRESERVE:
            moves.append(f"{stage}: moved {old.name} to {preserved.name}")
        elif plan.legacy is _Move.ENTRY:
            moves.append(
                f"{stage}: moved the pre-commit framework hook {old.name} to {entries.name}/{PRE_COMMIT_ENTRY}"
            )
        elif plan.legacy is _Move.REMOVE:
            moves.append(f"{stage}: replaced the devkit dispatcher pre-commit moved to {old.name}")
        if not dry_run:
            if plan.hook is _Move.PRESERVE:
                os.rename(path, preserved)
            elif plan.hook is _Move.ENTRY:
                os.replace(path, framework)
            try:
                changed |= _write(path, dispatcher_script(stage))
            except OSError:
                if plan.hook is _Move.PRESERVE:
                    os.rename(preserved, path)
                elif plan.hook is _Move.ENTRY:
                    os.rename(framework, path)
                raise
            if plan.legacy is _Move.PRESERVE:
                os.rename(old, preserved)
            elif plan.legacy is _Move.ENTRY:
                os.replace(old, framework)
            elif plan.legacy is _Move.REMOVE:
                old.unlink()
        else:
            changed |= _write(path, dispatcher_script(stage), dry_run=True)
        result.actions.extend(moves)
        if changed or moves:
            result.actions.append(f"{stage}: installed")
        if not dry_run:
            result.notices.extend(notices)


install = InstallHooksUseCase().execute


class UninstallHooksUseCase(BaseUseCase):
    """Application entrypoint for uninstall."""

    def execute(self, cwd: Path) -> InstallResult:
        """Remove owned devkit entries; retain the dispatcher and legacy adapter while user entries remain.

        Without user entries the dispatcher goes and the hooks it chained take its place: a pre-commit framework
        entry becomes the hook again, with a preserved hook as its ``<hook>.legacy`` (pre-commit's migration mode);
        otherwise the preserved hook is restored. When ``pre-commit install`` moved the dispatcher to
        ``<hook>.legacy`` (``chained_by_pre_commit``), pre-commit's hook stays and the preserved hook takes the
        dispatcher's place there. A preserved hook that cannot be chained is left in place and reported.
        """
        location = locate(cwd)
        actions: list[str] = []
        with clone_lock(location.directory.parent):
            for item in status(cwd, location):
                behind_pre_commit = item.state is not HookState.MANAGED and chained_by_pre_commit(item.path)
                if item.state is HookState.MANAGED or behind_pre_commit:
                    _uninstall_stage(item, behind_pre_commit, actions)
        return InstallResult(actions, hooks_dir=location.directory)


def _uninstall_stage(item: HookStatus, behind_pre_commit: bool, actions: list[str]) -> None:
    stage = item.stage
    entries = _entries(item.path)
    if entries.is_symlink() or (_present(entries) and not entries.is_dir()):
        raise HookLayoutError("hook script directory is not a regular directory", str(entries))
    entry = entries / DEVKIT_ENTRY
    if _owned(entry, GATE_MARKER):
        entry.unlink()
        actions.append(f"{stage}: removed {DEVKIT_ENTRY}")
    legacy = entries / LEGACY_ENTRY
    framework = entries / PRE_COMMIT_ENTRY
    chained = {legacy} if _owned(legacy, LEGACY_MARKER) else set()
    if generated_by_pre_commit(framework):
        chained.add(framework)
    remaining = list(entries.iterdir()) if entries.exists() else []
    if any(child not in chained for child in remaining):
        actions.append(f"{stage}: retained dispatcher for user scripts")
        return
    if legacy in chained:
        legacy.unlink()
    old = _pre_commit_legacy(item.path)
    backup = _backup(item.path)
    if behind_pre_commit:
        # pre-commit's hook stays at the hook path; an older copy of it in the entries would only run it twice.
        old.unlink()
        if framework in chained:
            framework.unlink()
        actions.append(f"{stage}: removed the dispatcher pre-commit runs as {old.name}")
        if _present(backup):
            os.rename(backup, old)
            actions.append(f"{stage}: restored {backup.name} as {old.name}")
    else:
        item.path.unlink()
        actions.append(f"{stage}: removed")
        if framework in chained:
            os.rename(framework, item.path)
            actions.append(f"{stage}: restored the pre-commit framework hook")
            if _present(backup) and not _present(old):
                os.rename(backup, old)
                actions.append(f"{stage}: restored {backup.name} as {old.name}")
            elif _present(backup):
                actions.append(
                    f"{stage}: left {backup.name} in place: {old.name} exists, so nothing runs it; "
                    "move it to the hook path or chain it by hand"
                )
        elif _present(backup):
            os.rename(backup, item.path)
            actions.append(f"{stage}: restored {backup.name}")
    if entries.exists():
        entries.rmdir()
